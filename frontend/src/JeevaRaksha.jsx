// ─── 3. VOICE-FIRST NAVIGATION ────────────────────────────────────────────────
function VoiceNavButton({ onNav }) {
  const { lang } = useLang();
  const [listening, setListening] = useState(false);
  const [status, setStatus] = useState("");
  const [show, setShow] = useState(false);

  const NAV_COMMANDS = {
    // English
    "home":["home","dashboard","main","start"],
    "symptom":["symptom","check","symptoms","disease","sick","ill"],
    "chat":["chat","talk","medbot","doctor","ask"],
    "emergency":["emergency","help","sos","ambulance","urgent"],
    "hospitals":["hospital","clinic","nearby","doctor","find"],
    "reminder":["medicine","reminder","tablet","pill","dose"],
    "library":["library","learn","health","info","read"],
    "ayurveda":["ayurveda","herbs","natural","home remedy","vaidya","herbal"],
    "outbreak":["outbreak","alert","disease","epidemic","warning","danger"],
    "profile":["profile","account","settings","me","my"],
  };

  const SCREEN_NAMES = {
    home:"Dashboard", symptom:"Symptom Checker", chat:"AI Chat",
    emergency:"Emergency", hospitals:"Nearby Hospitals", reminder:"Medicine Reminders",
    library:"Health Library", ayurveda:"Ayurveda AI", outbreak:"Disease Alerts", profile:"Profile"
  };

  const matchCommand = (transcript) => {
    const lower = transcript.toLowerCase();
    for (const [screen, keywords] of Object.entries(NAV_COMMANDS)) {
      if (keywords.some(k => lower.includes(k))) return screen;
    }
    return null;
  };

  const startVoiceNav = async () => {
    const SR = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!SR) { setStatus("Voice not supported in this browser"); setShow(true); setTimeout(()=>setShow(false),2500); return; }
    try {
      await navigator.mediaDevices.getUserMedia({ audio:true });
    } catch {
      setStatus("Microphone access denied"); setShow(true); setTimeout(()=>setShow(false),2500); return;
    }
    const recog = new SR();
    recog.lang = STT_LANG[lang] || "en-IN";
    recog.interimResults = false;
    recog.onstart = () => { setListening(true); setStatus("Listening... say a screen name"); setShow(true); };
    recog.onend = () => { setListening(false); setTimeout(()=>setShow(false), 2000); };
    recog.onresult = (e) => {
      const transcript = e.results[0][0].transcript;
      const match = matchCommand(transcript);
      if (match) {
        setStatus(`✅ Going to ${SCREEN_NAMES[match]}...`);
        speakText(`Opening ${SCREEN_NAMES[match]}`, STT_LANG[lang]||"en-IN");
        setTimeout(()=>{ onNav(match); setShow(false); }, 700);
      } else {
        setStatus(`❓ Didn't understand "${transcript}". Try again.`);
      }
    };
    recog.onerror = () => { setListening(false); setStatus("Error. Please try again."); };
    recog.start();
  };

  return (
    <div style={{ position:"relative" }}>
      {/* Floating voice nav popup */}
      {show && (
        <div style={{ position:"absolute", bottom:52, right:0, width:220, padding:"12px 14px", background:C.card, border:`1.5px solid ${listening?C.danger:C.accent}`, borderRadius:14, boxShadow:`0 8px 30px #00000060`, animation:"fadeUp 0.3s ease", zIndex:100 }}>
          <div style={{ fontSize:11, fontWeight:700, color: listening?C.danger:C.accent, marginBottom:6 }}>
            {listening ? "🎤 LISTENING..." : "🗣️ Voice Navigation"}
          </div>
          <div style={{ fontSize:12, color:C.textSub, lineHeight:1.5 }}>{status}</div>
          {listening && (
            <div style={{ display:"flex", gap:3, alignItems:"flex-end", marginTop:8, justifyContent:"center" }}>
              {[4,8,6,10,5,9,4,7,3].map((h,i)=>(
                <div key={i} style={{ width:3, height:h, background:C.danger, borderRadius:2, animation:`typingDot 0.6s ${i*0.08}s ease-in-out infinite` }}/>
              ))}
            </div>
          )}
          {!listening && (
            <div style={{ marginTop:8, fontSize:10, color:C.muted }}>
              Say: "Symptoms", "Chat", "Emergency", "Ayurveda", "Hospitals"...
            </div>
          )}
        </div>
      )}

      {/* Voice button */}
      <button onClick={startVoiceNav} title="Voice Navigation — say a screen name"
        style={{ width:44, height:44, borderRadius:12, border:`1.5px solid ${listening?C.danger:C.border}`, background: listening?`linear-gradient(135deg,${C.danger},#C41E3A)`:C.card, cursor:"pointer", display:"flex", alignItems:"center", justifyContent:"center", transition:"all 0.25s", boxShadow:listening?`0 0 0 4px ${C.danger}33`:C.accentGlow, position:"relative" }}>
        {listening && <div style={{ position:"absolute", inset:-5, borderRadius:15, border:`2px solid ${C.danger}55`, animation:"ping 1s ease-out infinite", pointerEvents:"none" }}/>}
        <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke={listening?"#fff":C.textSub} strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round">
          <path d="M12 1a3 3 0 0 0-3 3v8a3 3 0 0 0 6 0V4a3 3 0 0 0-3-3z"/>
          <path d="M19 10v2a7 7 0 0 1-14 0v-2"/>
          <line x1="12" y1="19" x2="12" y2="23"/>
          <line x1="8" y1="23" x2="16" y2="23"/>
        </svg>
      </button>
    </div>
  );
}

