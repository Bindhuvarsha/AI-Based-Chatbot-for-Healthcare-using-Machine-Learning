function Field({
  label,
  type="text",
  value,
  onChange,
  placeholder,
  icon,
  error,
  hint,
  options=[],
  autoFocus=false,
}) {
  const base = {
    width:"100%",
    padding: icon ? "11px 12px 11px 36px" : "11px 12px",
    borderRadius:10,
    border:`1.5px solid ${error ? C.danger : C.border}`,
    background:C.card,
    color:C.text,
    fontSize:13,
    outline:"none",
  };

  return (
    <div style={{ marginBottom:12 }}>
      {label && <div style={{ fontSize:11, color:C.muted, fontWeight:700, marginBottom:6, letterSpacing:0.3 }}>{label}</div>}
      <div style={{ position:"relative" }}>
        {icon && <span style={{ position:"absolute", left:11, top:"50%", transform:"translateY(-50%)", fontSize:14, opacity:0.9 }}>{icon}</span>}
        {type === "select" ? (
          <select
            value={value ?? ""}
            onChange={e => onChange?.(e.target.value)}
            style={base}
            autoFocus={autoFocus}
          >
            {options.map((opt, i) => {
              const o = typeof opt === "string" ? { value:opt, label:opt } : opt;
              return <option key={`${o.value}-${i}`} value={o.value}>{o.label}</option>;
            })}
          </select>
        ) : (
          <input
            type={type}
            value={value ?? ""}
            onChange={e => onChange?.(e.target.value)}
            placeholder={placeholder}
            style={base}
            autoFocus={autoFocus}
          />
        )}
      </div>
      {error && <div style={{ fontSize:11, color:C.danger, marginTop:3, paddingLeft:2 }}>⚠ {error}</div>}
      {hint && !error && <div style={{ fontSize:11, color:C.muted, marginTop:3, paddingLeft:2 }}>{hint}</div>}
    </div>
  );
}

