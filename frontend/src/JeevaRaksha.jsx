// Picks the best available voice with graceful fallbacks.
function pickVoice(langCode) {
  const voices = window.speechSynthesis.getVoices();
  if (!voices.length) return null;
  const base = langCode.split("-")[0]; // e.g. "kn" from "kn-IN"
  // Priority 1: exact locale match (e.g. "kn-IN")
  let v = voices.find(x => x.lang === langCode);
  // Priority 2: same language prefix (e.g. starts with "kn")
  if (!v) v = voices.find(x => x.lang.startsWith(base));
  // Priority 3: Indian English as fallback for scripts without a TTS voice
  if (!v) v = voices.find(x => x.lang === "en-IN");
  // Priority 4: any English voice
  if (!v) v = voices.find(x => x.lang.startsWith("en"));
  return v || null;
}

function doSpeak(text, langCode, onEnd) {
  if (!window.speechSynthesis) return;
  window.speechSynthesis.cancel();
  // Strip markdown / emoji that sound bad when read aloud
  const clean = text.replace(/[*_~`#⚠️👋✓✔️💊🔬💬🚨👤🏥💧🚶😴🥦🧼🔥👣🩺]/gu, "").trim();
  const utt = new SpeechSynthesisUtterance(clean);
  utt.lang = langCode || "en-IN";
  utt.rate = 0.92;
  utt.pitch = 1.05;
  const voice = pickVoice(utt.lang);
  if (voice) utt.voice = voice;
  if (onEnd) { utt.onend = onEnd; utt.onerror = onEnd; }
  window.speechSynthesis.speak(utt);
}

// Public helper — waits for voices to be ready before speaking.
function speakText(text, langCode, onEnd) {
  if (!window.speechSynthesis) return;
  const voices = window.speechSynthesis.getVoices();
  if (voices.length > 0) {
    doSpeak(text, langCode, onEnd);
  } else {
    // Voices not yet loaded — wait for the browser event
    const handler = () => {
      window.speechSynthesis.removeEventListener("voiceschanged", handler);
      doSpeak(text, langCode, onEnd);
    };
    window.speechSynthesis.addEventListener("voiceschanged", handler);
  }
}

