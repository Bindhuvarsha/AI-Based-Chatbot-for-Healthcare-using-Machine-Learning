// ─── AUDIO ENGINE ─────────────────────────────────────────────────────────────
let _audioCtx = null;
let _masterGain = null;
let _alarmNodes = []; // track all running nodes so we can stop them

function getAudioCtx() {
  if (!_audioCtx || _audioCtx.state === "closed") {
    _audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    _masterGain = _audioCtx.createGain();
    _masterGain.gain.value = 0.85;
    _masterGain.connect(_audioCtx.destination);
  }
  if (_audioCtx.state === "suspended") _audioCtx.resume();
  return _audioCtx;
}

function stopAllAlarmSounds() {
  _alarmNodes.forEach(n => { try { n.stop(); } catch(e){} });
  _alarmNodes = [];
}

// ── Note helper ───────────────────────────────────────────────────────────────
// type: "sine"|"square"|"triangle"|"sawtooth"
function scheduleNote(ctx, dest, freq, startT, dur, vol=0.6, type="sine", attack=0.01, release=0.06) {
  const osc  = ctx.createOscillator();
  const gain = ctx.createGain();
  osc.type = type;
  osc.frequency.value = freq;
  osc.connect(gain);
  gain.connect(dest);
  gain.gain.setValueAtTime(0, startT);
  gain.gain.linearRampToValueAtTime(vol, startT + attack);
  gain.gain.setValueAtTime(vol, startT + dur - release);
  gain.gain.linearRampToValueAtTime(0, startT + dur);
  osc.start(startT);
  osc.stop(startT + dur + 0.05);
  _alarmNodes.push(osc);
}

// ── Musical ringtone: "Joyful Medicine Bell" ──────────────────────────────────
// A cheerful, impossible-to-ignore Indian-style alarm melody
function playAlarmSound() {
  try {
    const ctx = getAudioCtx();
    const dest = _masterGain;
    const t = ctx.currentTime + 0.05;

    // Note frequencies
    const C5=523, D5=587, E5=659, F5=698, G5=784, A5=880, B5=988, C6=1047;
    const E4=330, G4=392, C4=262;

    // ── MELODY (bright sine, main tune) ───────────────────────────────────
    // Pattern: joyful ascending call-and-response
    const mel = [
      [C5,0.18],[E5,0.18],[G5,0.18],[C6,0.30],
      [B5,0.12],[A5,0.12],[G5,0.30],
      [E5,0.18],[G5,0.18],[A5,0.18],[C6,0.30],
      [G5,0.18],[E5,0.18],[C5,0.40],
    ];
    let mt = t;
    mel.forEach(([freq, dur]) => {
      scheduleNote(ctx, dest, freq, mt, dur, 0.55, "sine", 0.01, 0.05);
      mt += dur + 0.03;
    });

    // ── HARMONY (triangle, softer lower octave) ───────────────────────────
    const har = [
      [C4,0.36],[E4,0.36],[G4,0.36],[C5,0.30],
      [G4,0.24],[E4,0.30],
      [C4,0.36],[E4,0.36],[F5,0.18],[C5,0.30],
      [G4,0.36],[C4,0.40],
    ];
    let ht = t;
    har.forEach(([freq, dur]) => {
      scheduleNote(ctx, dest, freq, ht, dur, 0.3, "triangle", 0.02, 0.08);
      ht += dur + 0.03;
    });

    // ── BELL ACCENT (short high sine pings on beat) ───────────────────────
    const bells = [t, t+0.72, t+1.44, t+2.16];
    bells.forEach(bt => scheduleNote(ctx, dest, C6*2, bt, 0.10, 0.4, "sine", 0.005, 0.09));

    // ── RHYTHM PULSE (sawtooth low kick feel) ─────────────────────────────
    for (let i=0; i<8; i++) {
      scheduleNote(ctx, dest, 80, t + i*0.36, 0.08, 0.18, "sawtooth", 0.005, 0.07);
    }

    // Total duration ~2.8s, called every 3.2s = seamless loop

  } catch(e) { console.warn("Audio error:", e); }
}

